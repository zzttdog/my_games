  'use strict';
  function webp(src) {
    if (!src || typeof src !== 'string') return src;
    if (/^(?:data:|blob:|https?:)/i.test(src)) return src;
    if (/\.webp(?:[?#]|$)/i.test(src)) return src;
    return /\.(?:jpe?g|png)(?:[?#]|$)/i.test(src)
      ? src.replace(/(\.(?:jpe?g|png))(?=[?#]|$)/i, '$1.webp')
      : src;
  }
